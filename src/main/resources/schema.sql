-- Hostel Complaint & Maintenance Tracker schema (H2 + PostgreSQL compatible)

CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,          -- STUDENT | WARDEN | STAFF
    room_no       VARCHAR(20),
    phone         VARCHAR(20),
    speciality    VARCHAR(40),                    -- staff only: ELECTRICITY, PLUMBING ...
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS complaints (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(120)  NOT NULL,
    description     VARCHAR(1000) NOT NULL,
    category        VARCHAR(40)   NOT NULL,
    priority        VARCHAR(10)   NOT NULL,       -- LOW | MEDIUM | HIGH
    status          VARCHAR(20)   NOT NULL,       -- OPEN | IN_PROGRESS | RESOLVED
    room_no         VARCHAR(20)   NOT NULL,
    student_id      BIGINT        NOT NULL REFERENCES users(id),
    assigned_to     BIGINT        REFERENCES users(id),
    resolution_note VARCHAR(500),
    created_at      TIMESTAMP     NOT NULL,
    assigned_at     TIMESTAMP,
    resolved_at     TIMESTAMP
);

-- Every status change is recorded here: this powers the timeline on the complaint page
CREATE TABLE IF NOT EXISTS complaint_updates (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id BIGINT       NOT NULL REFERENCES complaints(id) ON DELETE CASCADE,
    status       VARCHAR(20)  NOT NULL,
    note         VARCHAR(500),
    updated_by   BIGINT       REFERENCES users(id),
    created_at   TIMESTAMP    NOT NULL
);
